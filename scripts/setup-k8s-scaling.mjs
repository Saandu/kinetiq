import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import YAML from 'yaml';
import { root, toolDirectory, run, tool, kubeconfig } from './setup-k8s-tools.mjs';
import { apply, assertLocalCluster, kubectl, namespace, capture } from './local-kubernetes.mjs';
import { validateLocalScaling } from './local-scaling.mjs';

assertLocalCluster();
const objects = YAML.parseAllDocuments(await readFile(path.join(root, 'infra/k8s/local/scaling.yaml'), 'utf8')).map(document => document.toJSON());
validateLocalScaling(objects);
const pins = JSON.parse(await readFile(path.join(root, 'infra/k8s/local/keda.json'), 'utf8'));
const directory = path.join(toolDirectory, 'platform');
await mkdir(directory, { recursive: true });
const archive = path.join(directory, 'keda-2.21.0.tgz');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
let bytes;
try { bytes = await readFile(archive); } catch (error) { if (error.code !== 'ENOENT') throw error; }
if (!bytes || hash(bytes) !== pins.sha256) {
  const response = await fetch(pins.url, { signal: AbortSignal.timeout(120_000) });
  if (!response.ok) throw new Error(`KEDA download failed: ${response.status}`);
  bytes = Buffer.from(await response.arrayBuffer());
  if (hash(bytes) !== pins.sha256) throw new Error('KEDA checksum mismatch');
  await writeFile(archive, bytes);
}
const resources = { requests: { cpu: '50m', memory: '64Mi' }, limits: { cpu: '500m', memory: '192Mi' } };
const values = path.join(directory, 'keda-values.yaml');
await writeFile(values, YAML.stringify({
  watchNamespace: namespace, image: Object.fromEntries(Object.entries(pins.images).map(([name, tag]) => [name, { tag }])),
  resources: { operator: resources, metricServer: resources, webhooks: resources },
  certificates: { autoGenerated: false, certManager: { enabled: true } },
}));
run(tool('helm'), ['upgrade', '--install', 'keda', archive, '--kubeconfig', kubeconfig,
  '--namespace', 'keda', '--create-namespace', '--values', values, '--wait', '--timeout', '240s']);
const apiIp = kubectl(['get', 'service', 'kubernetes', '-n', 'default', '-o', 'jsonpath={.spec.clusterIP}'], capture).trim();
const nodeIp = kubectl(['get', 'node', 'k3d-kinetiq-local-server-0', '-o', 'jsonpath={.status.addresses[?(@.type=="InternalIP")].address}'], capture).trim();
if (![apiIp, nodeIp].every(ip => /^\d{1,3}(\.\d{1,3}){3}$/.test(ip))) throw new Error('Expected local IPv4 API addresses');
apply([{ apiVersion: 'networking.k8s.io/v1', kind: 'NetworkPolicy', metadata: { name: 'keda-local-boundary', namespace: 'keda' }, spec: {
  podSelector: {}, policyTypes: ['Ingress', 'Egress'],
  ingress: [{ from: [{ namespaceSelector: { matchLabels: { 'kubernetes.io/metadata.name': 'keda' } } }] },
    { from: [{ ipBlock: { cidr: `${nodeIp}/32` } }], ports: [{ protocol: 'TCP', port: 6443 }, { protocol: 'TCP', port: 9443 }] }],
  egress: [{ to: [{ namespaceSelector: { matchLabels: { 'kubernetes.io/metadata.name': 'keda' } } }] },
    { to: [{ namespaceSelector: { matchLabels: { 'kubernetes.io/metadata.name': 'kube-system' } }, podSelector: { matchLabels: { 'k8s-app': 'kube-dns' } } }],
      ports: [{ protocol: 'UDP', port: 53 }, { protocol: 'TCP', port: 53 }] },
    { to: [{ ipBlock: { cidr: `${apiIp}/32` } }, { ipBlock: { cidr: `${nodeIp}/32` } }], ports: [{ protocol: 'TCP', port: 443 }, { protocol: 'TCP', port: 6443 }] },
    { to: [{ namespaceSelector: { matchLabels: { 'kubernetes.io/metadata.name': namespace } }, podSelector: { matchLabels: { 'app.kubernetes.io/component': 'localstack' } } }], ports: [{ protocol: 'TCP', port: 4566 }] }],
} }]);
// Only fake emulator credentials; the endpoint and egress below prevent real AWS access.
apply([{ apiVersion: 'v1', kind: 'Secret', metadata: { name: 'kinetiq-keda-local', namespace },
  stringData: { accessKey: 'test', secretKey: 'test' } },
{ apiVersion: 'networking.k8s.io/v1', kind: 'NetworkPolicy', metadata: { name: 'keda-localstack', namespace }, spec: {
  podSelector: { matchLabels: { 'app.kubernetes.io/component': 'localstack' } }, policyTypes: ['Ingress'],
  ingress: [{ from: [{ namespaceSelector: { matchLabels: { 'kubernetes.io/metadata.name': 'keda' } },
    podSelector: { matchLabels: { 'app.kubernetes.io/name': 'keda-operator' } } }], ports: [{ protocol: 'TCP', port: 4566 }] }],
} }]);
// Reserve peak worker limits, rolling surges and setup Jobs before enabling scaling.
const deploys = JSON.parse(kubectl(['get', 'deploy', '-n', namespace, '-l', 'app.kubernetes.io/instance=kinetiq', '-o', 'json'], capture)).items;
let appMi = 512;
for (const deploy of deploys.filter(item => item.metadata.name.startsWith('kinetiq-'))) {
  const component = deploy.metadata.labels['app.kubernetes.io/component'];
  const replicas = component === 'ingest' ? 3 : deploy.spec.replicas;
  const surge = ['simulator', 'local-bridge'].includes(component) ? 0 : 1;
  appMi += Number.parseInt(deploy.spec.template.spec.containers[0].resources.limits.memory) * (replicas + surge);
}
if (appMi > 2560) throw new Error(`Peak application budget exceeded: ${appMi} MiB`);
const apiReplicas = deploys.find(item => item.metadata.name === 'kinetiq-api').spec.replicas;
// 5 per API Pod + 3 per worker, plus one API/worker rolling surge and maintenance reserve.
if (apiReplicas * 5 + 3 * 3 + 5 + 3 + 15 > 50) throw new Error('Database connection budget exceeded');
apply(objects);
kubectl(['wait', 'scaledobject/kinetiq-ingest', '-n', namespace, '--for=condition=Ready', '--timeout=120s']);
console.log(`KEDA ready: ingest bounded to 1–3 replicas; peak application budget ${appMi} MiB, KEDA limits 576 MiB.`);
